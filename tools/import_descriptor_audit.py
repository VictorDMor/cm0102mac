def require_import_descriptor_contract(page, instructions, selected=None):
    if page not in (0x1077f, 0x10780, 0x10781): return
    addresses = {r['address'] for r in instructions} | set(selected or ())
    for start, end, count, expected in CONTRACTS:
        if not start >> 12 <= page <= (end - 1) >> 12: continue
        low, high = max(start, page << 12), min(end, (page + 1) << 12)
        if start not in addresses and not any(low <= a < high for a in addresses): continue
        if start >> 12 != (end - 1) >> 12:
            _, _, count, expected = next(c for c in FRAGMENT_CONTRACTS if c[:2] == (start, page))
        body = [r for r in instructions if low <= r['address'] < high]
        if len(body) != count or fingerprint(body) != expected:
            raise ValueError(f'Import-descriptor page fragment changed at {start:x}/{page:x}')


def require_import_descriptor_index(db, selected=None):
    records = [json.loads(row[0]) for row in db.execute(
        'SELECT body FROM instructions WHERE address>=? AND address<? ORDER BY address',
        (CONTRACTS[0][0], CONTRACTS[-1][1]))]
    if selected is None: require_import_descriptor_bodies(records, complete=True)
    else:
        ordered = [r for _, r in sorted(selected.items())]
        for page in (0x1077f, 0x10780, 0x10781):
            require_import_descriptor_contract(page, [r for r in ordered if r['address'] >> 12 == page], selected)
    require_import_descriptor_edges(db.execute("""SELECT i.address,e.value
        FROM instructions AS i,
          json_each(json_insert(json_extract(i.body,'$.flows'),'$[#]',json_extract(i.body,'$.fallthrough'))) AS e
        WHERE e.value>=? AND e.value<?""", (CONTRACTS[0][0], CONTRACTS[-1][1])))


def import_descriptor_hook(entry):
    return f'if (try_modern_import_descriptor(s, 0x{entry:x})) return true;'


def require_import_descriptor_hooks(page, instructions, code):
    addresses = {r['address'] for r in instructions}
    for entry in IMPORT_DESCRIPTOR_ENTRIES:
        if entry >> 12 != page or entry not in addresses: continue
        label, hook, step = f'i_{entry:x}:', import_descriptor_hook(entry), f's.step(0x{entry:x});'
        fragment = code.split(label, 1)[-1].split(f'i_{entry + 4:x}:', 1)[0]
        if code.count(hook) != 1 or hook not in fragment or step not in fragment or fragment.index(hook) > fragment.index(step):
            raise ValueError(f'Missing or misplaced import-descriptor hook at {entry:x}')
