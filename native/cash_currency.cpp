std::uint32_t configure(Cpu& c,unsigned currency) {
    Frame frame(c,0x1000a440,0x80,{.first_gpr=24});Program p{c};
    const auto pool=c.toc(-0x59d8),numbers=c.toc(-0x59d4),buffer=c.toc(-0x7ba8);
    keep(c,{{31,currency},{24,c.toc(-0x59f0)},{25,c.toc(-0x59ec)},
            {26,c.toc(-0x59e8)},{27,c.toc(-0x59e4)},{28,c.toc(-0x59e0)},
            {29,buffer},{30,pool}});
    c.set(5,numbers);c.set(3,c.toc(-0x59d0));
    const auto selected=signed_byte(currency);
    if(compare_logical(c,selected,24)>0) {
        assertion(c,frame,0x1000b0f0,pool,buffer,0x40,0x38,0x252);
        c.set(4,c.toc(-0x7bac));c.put8(c.r(4),0);return result(c,0);
    }
    const auto destination=c.u32(c.toc(-0x59f4)+selected*4);
    const auto found=std::ranges::find(currencies,destination,&Currency::destination);
    if(found==currencies.end())throw std::runtime_error("Invalid CASH currency branch");
    const auto& profile=*found;
    // All numeric sources are loaded before the first store/copy. Keep the
    // original reuse of f0/f1/f2 and the two-load store order for aliases.
    if(profile.loads==Currency::one) {
        c.set_f(0,c.f64(numbers+profile.scale));
        for(auto slot:{0x3aecu,0x3af4u,0x3afcu})c.put_f64(c.r(2)-slot,c.f(0));
    }else if(profile.loads==Currency::two) {
        c.set_f(0,c.f64(numbers+profile.unit_scale));c.set_f(1,c.f64(numbers+profile.scale));
        c.put_f64(c.r(2)-0x3af4,c.f(0));c.put_f64(c.r(2)-0x3aec,c.f(1));c.put_f64(c.r(2)-0x3afc,c.f(0));
    }else{
        c.set_f(2,c.f64(numbers+profile.scale));c.set_f(1,c.f64(numbers+profile.unit_scale));c.set_f(0,c.f64(numbers+profile.step_scale));
        c.put_f64(c.r(2)-0x3aec,c.f(2));c.put_f64(c.r(2)-0x3af4,c.f(1));c.put_f64(c.r(2)-0x3afc,c.f(0));
    }
    const unsigned first_back=destination+(profile.loads==Currency::three?0x20:profile.loads==Currency::two?0x1c:0x18);
    p.call(0x1077dbf0,first_back,{c.r(3),pool+profile.symbol});
    for(unsigned n=0;n<5;++n)p.call(0x1077dbf0,first_back+12*(n+1),{c.r(28-n),pool+profile.suffixes[n]});
    c.set(4,profile.decimal);c.put8(c.r(2)-0x3aff,profile.grouping);
    c.put8(c.r(2)-0x3b00,profile.decimal);c.put8(c.r(2)-0x3b01,profile.four_digits);
    c.put8(c.r(2)-0x3b02,c.r(31));return result(c,1);
}
std::uint32_t setting(Cpu& c) {return result(c,c.u8(c.r(2)-0x3b02));}
std::uint32_t symbol_length(Cpu& c) {
    Frame frame(c,0x10009ef0,0x40,{});Program p{c};
    return result(c,signed_byte(p.call(0x1077dbd0,0x10009f04,{c.toc(-0x59d0)})));
}
std::uint32_t label(Cpu& c,unsigned output,unsigned capacity,unsigned currency) {
    Frame frame(c,0x1000b160,0xa0,{.first_gpr=29});Program p{c};
    const auto pool=c.toc(-0x59d8),buffer=c.toc(-0x7ba8),success=c.toc(-0x7bac);
    keep(c,{{31,pool},{30,buffer},{29,success}});
    bool valid=compare_logical(c,output)!=0;
    if(valid)valid=compare(c,std::int16_t(capacity),50)>=0;
    if(!valid) {
        assertion(c,frame,0x1000b1ac,pool,buffer,0x68,0x40,0x272);
        c.put8(c.r(29),0);return result(c,0);
    }
    const auto selected=signed_byte(currency);
    if(compare_logical(c,selected,24)>0) {
        assertion(c,frame,0x1000b3b4,pool,buffer,0x48,0x38,0x2c5);
        c.put8(c.r(29),0);return result(c,0);
    }
    const auto destination=c.u32(c.toc(-0x59f8)+selected*4);
    constexpr std::array offsets{0x13bu,0x165u,0x16au,0x16fu,0x173u,0x178u,0x5du,0x17du,0x182u,
        0x189u,0x18du,0x190u,0x194u,0x19cu,0x1a0u,0xceu,0x1a5u,0x1a9u,0x1afu,0x1b6u,0x1bcu,
        0x1c0u,0x1c4u,0x1c8u,0x1cu};
    if(destination<0x1000b210 || destination>0x1000b390 || (destination-0x1000b210)%16)
        throw std::runtime_error("Invalid CASH label branch");
    p.call(0x1077dbf0,destination+8,{output,pool+offsets[(destination-0x1000b210)/16]});
    return result(c,1);
}
