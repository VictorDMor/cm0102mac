void lay_out_formation(Cpu& c, std::uint32_t, std::uint32_t plan_address) {
    // Frameless: `stmw r23,-0x24(r1)` saves r23-r31 below the stack pointer
    // (the cases use them as scratch); `lmw` restores them from there.
    for (unsigned n = 23; n < 32; ++n) c.put32(c.sp() - 0x24 + (n - 23) * 4, c.r(n));
    const ClubEntry plan{c, plan_address};
    const std::uint32_t slots = plan.rows();
    for (std::uint32_t i = 0; i < std::uint32_t(squads::slot_count); ++i) {
        const Row slot{c, slots + i * Row::size};
        if (i < std::uint32_t(squads::player_slots)) {
            slot.kind() = Row::player;
            continue;
        }
        slot.set_category(1);
        slot.kind() = staff_jobs[i - squads::player_slots];
    }
    // cmplwi on the sign-extended formation: a negative one takes case 0.
    const std::uint32_t formation = std::uint32_t(std::int32_t(plan.formation()));
    const auto& layout = layouts[compare_logical(c, formation, 9) > 0 ? 0 : formation];
    for (std::uint32_t k = 0; k < layout.positions.size(); ++k) c.put16(slots + 2 + k * Row::size, layout.positions[k]);
    for (unsigned n = 0; n < layout.left.size(); ++n) {
        const auto value = layout.left[n];
        c.set(3 + n, value == left_slots ? slots : value == left_plan ? plan_address : value);
    }
}
