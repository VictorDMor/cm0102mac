std::uint32_t multiply_high(std::uint32_t left, std::uint32_t right) {
    const auto product = std::int64_t(std::int32_t(left)) * std::int32_t(right);
    return std::uint32_t(std::uint64_t(product) >> 32);
}

std::uint32_t arithmetic_shift(Cpu& c, std::uint32_t value, unsigned count) {
    const auto signed_value = std::int32_t(value);
    c.s.wr<1>(reg::xer_ca, signed_value < 0 && (value & ((1u << count) - 1)));
    return std::uint32_t(signed_value >> count);
}

std::uint32_t add_saved_carry(Cpu& c, std::uint32_t value) {
    const auto sum = std::uint64_t(value) + c.s.r<1>(reg::xer_ca);
    c.s.wr<1>(reg::xer_ca, sum >> 32);
    return sum;
}
